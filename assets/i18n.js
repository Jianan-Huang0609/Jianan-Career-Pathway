/* ============================================================
   Language switching
   ============================================================ */
let currentLang = "zh-CN";

function applyLang(lang) {
  currentLang = lang;
  const dict = I18N[lang];
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
  const btn = document.getElementById("langToggle");
  if (btn) btn.textContent = lang === "en" ? "中文" : "EN";
  try { localStorage.setItem("career-lang", lang); } catch (e) {}
}

function toggleLang() {
  applyLang(currentLang === "zh-CN" ? "en" : "zh-CN");
}

/* ============================================================
   Scroll progress bar
   ============================================================ */
function initProgress() {
  const bar = document.getElementById("progressBar");
  if (!bar) return;
  const update = () => {
    const scrollTop = window.scrollY;
    const scrollHeight = document.documentElement.scrollHeight - window.innerHeight;
    const progress = scrollHeight > 0 ? (scrollTop / scrollHeight) * 100 : 0;
    bar.style.width = progress + "%";
  };
  window.addEventListener("scroll", () => requestAnimationFrame(update), { passive: true });
  update();
}

/* ============================================================
   Scroll-triggered reveal (Apple fade-up)
   ============================================================ */
function initReveal() {
  document.querySelectorAll(".stagger-children").forEach(parent => {
    Array.from(parent.children).forEach((child, i) => {
      child.style.setProperty("--stagger-index", i);
    });
  });
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      }
    });
  }, { rootMargin: "0px 0px -15% 0px", threshold: 0.1 });
  document.querySelectorAll(".animate-in").forEach(el => observer.observe(el));
}

/* ============================================================
   Keyboard navigation (arrow keys)
   ============================================================ */
function initKeyboard() {
  const sections = Array.from(document.querySelectorAll(".module"));
  document.addEventListener("keydown", (e) => {
    if (["INPUT", "TEXTAREA"].includes(e.target.tagName)) return;
    const current = sections.findIndex(s => {
      const r = s.getBoundingClientRect();
      return r.top <= window.innerHeight / 2 && r.bottom > window.innerHeight / 2;
    });
    if (e.key === "ArrowDown" || e.key === "ArrowRight" || e.key === "PageDown") {
      const next = sections[Math.min(current + 1, sections.length - 1)];
      if (next) { next.scrollIntoView({ behavior: "smooth" }); e.preventDefault(); }
    }
    if (e.key === "ArrowUp" || e.key === "ArrowLeft" || e.key === "PageUp") {
      const prev = sections[Math.max(current - 1, 0)];
      if (prev) { prev.scrollIntoView({ behavior: "smooth" }); e.preventDefault(); }
    }
  });
}

document.addEventListener("DOMContentLoaded", () => {
  let saved = null;
  try { saved = localStorage.getItem("career-lang"); } catch (e) {}
  applyLang(saved === "en" ? "en" : "zh-CN");
  initProgress();
  initReveal();
  initKeyboard();
});
